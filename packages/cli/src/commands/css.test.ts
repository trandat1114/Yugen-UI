import fs from "node:fs";
import path from "node:path";
import { describe, expect, it } from "vitest";
import { findGenerated, parseRecorded, replaceThemeImports } from "../lib/leanCss.js";
import { FIXTURE_MANIFEST, installYugen, tmpDir, viteProject, writeFiles } from "../test/fixtures.js";
import { add } from "./add.js";
import { css } from "./css.js";
import { diagnose } from "./doctor.js";
import { init } from "./init.js";

const ctx = { interactive: false };
const read = (cwd: string, file: string) => fs.readFileSync(path.join(cwd, file), "utf8");
/** Dòng @import của file sinh ra (bỏ phần chú thích đầu file). */
const imports = (cwd: string, file = "src/yugen-ui.css") => read(cwd, file).split("\n").filter((l) => l.startsWith("@import"));

const APP = `import { Button, type ButtonProps } from "yugen-ui";
import type { DialogProps } from "yugen-ui";
import { NavItem as Item } from "yugen-ui";
// import { Dialog } from "yugen-ui";
/* import { toast } from "yugen-ui"; */
const sample = \`import { Dialog } from "yugen-ui";\`;
const quoted = 'import { Toast } from "yugen-ui"';
const pattern = /import { AppShell } from "yugen-ui"/;
export function App(props: ButtonProps) {
  return (
    <main>
      <p>Don't write import {"{ Dialog }"} from "yugen-ui" here: https://example.com // not a comment</p>
      <Button {...props}>
        <Item href="/">Home</Item>
      </Button>
    </main>
  );
}
`;

describe("yugen css", () => {
  it("writes theme-core.css and one line per imported folder; imports in strings, comments, regexes, JSX text and types don't count", async () => {
    const cwd = installYugen(
      viteProject({
        "src/index.css": '@import "tailwindcss";\n@import "yugen-ui/theme.css";\n\nbody { margin: 0; }\n',
        "src/App.tsx": APP,
        "src/main.tsx": 'import { YugenProvider } from "yugen-ui/YugenProvider";\nimport "./index.css";\n',
        "src/hooks.ts": 'export { useMediaQuery } from "yugen-ui";\n',
        "dist/old.js": 'import { Dialog } from "yugen-ui";\n',
      }),
    );
    const result = await css({ cwd });
    expect(result).toMatchObject({ file: "src/yugen-ui.css", folders: ["Button", "Nav", "YugenProvider", "hooks"], everything: false, written: true });
    expect(imports(cwd)).toEqual([
      '@import "yugen-ui/theme-core.css";',
      '@import "yugen-ui/sources/Button.css";',
      '@import "yugen-ui/sources/Nav.css";',
      '@import "yugen-ui/sources/YugenProvider.css";',
      '@import "yugen-ui/sources/hooks.css";',
    ]);
    expect(read(cwd, "src/yugen-ui.css")).toMatch(/^\/\*\n \* Generated by `yugen css` from the yugen-ui imports in your code/);
    // theme.css is replaced in place, below "tailwindcss".
    expect(read(cwd, "src/index.css")).toBe('@import "tailwindcss";\n@import "./yugen-ui.css";\n\nbody { margin: 0; }\n');

    // Second run: nothing to write, still one import.
    expect((await css({ cwd })).written).toBe(false);
    expect(read(cwd, "src/index.css").match(/yugen-ui\.css/g)).toHaveLength(1);
  });

  it("brand web / teams adds tokens/brands.css when the package has token groups (#354); older packages don't", async () => {
    const app = (brand: string) => `import { YugenProvider } from "yugen-ui";
export const app = <YugenProvider brand="${brand}" />;
`;
    const files = { "src/main.tsx": app("teams") };
    const withTokens = installYugen(viteProject(files), { ...FIXTURE_MANIFEST, tokens: { brands: "tokens/brands.css", charts: "tokens/charts.css" } });
    await css({ cwd: withTokens });
    expect(imports(withTokens)).toEqual([
      '@import "yugen-ui/theme-core.css";',
      '@import "yugen-ui/tokens/brands.css";',
      '@import "yugen-ui/sources/YugenProvider.css";',
    ]);

    const sakura = installYugen(viteProject({ "src/main.tsx": app("sakura") }), { ...FIXTURE_MANIFEST, tokens: { brands: "tokens/brands.css" } });
    await css({ cwd: sakura });
    expect(imports(sakura)).not.toContain('@import "yugen-ui/tokens/brands.css";');

    const older = installYugen(viteProject(files));
    await css({ cwd: older });
    expect(imports(older)).toEqual(['@import "yugen-ui/theme-core.css";', '@import "yugen-ui/sources/YugenProvider.css";']);
  });

  it("--check exits with 1 when the file is out of date; yugen add (package mode) adds the component", async () => {
    const cwd = installYugen(viteProject({ "src/App.tsx": 'import { Button } from "yugen-ui";\n' }));
    expect((await css({ cwd, check: true })).ok).toBe(false);
    expect(fs.existsSync(path.join(cwd, "src/yugen-ui.css"))).toBe(false);
    await css({ cwd });
    expect(read(cwd, "src/index.css")).toBe('@import "tailwindcss";\n@import "./yugen-ui.css";\n\nbody { margin: 0; }\n');
    expect((await css({ cwd, check: true })).ok).toBe(true);

    fs.appendFileSync(path.join(cwd, "src/App.tsx"), 'import { DialogTrigger } from "yugen-ui";\n');
    expect((await css({ cwd, check: true })).ok).toBe(false);
    expect((await css({ cwd })).folders).toEqual(["Button", "Dialog"]);
    expect((await css({ cwd, check: true })).ok).toBe(true);

    // `yugen add toast` in package mode: prints the import and adds Toast before the code uses it.
    fs.writeFileSync(path.join(cwd, "yugen.json"), JSON.stringify({ mode: "package", framework: "vite", rsc: false, css: "src/index.css" }));
    await add({ cwd, names: ["toast"] }, ctx);
    expect(imports(cwd)).toContain('@import "yugen-ui/sources/Toast.css";');
  });

  it("falls back to theme.css for namespace imports, export * and import()", async () => {
    for (const code of ['import * as Yugen from "yugen-ui";\n', 'export * from "yugen-ui";\n', 'const m = await import("yugen-ui");\n']) {
      const cwd = installYugen(viteProject({ "src/App.tsx": `import { Button } from "yugen-ui";\n${code}` }));
      const result = await css({ cwd });
      expect(result.everything).toBe(true);
      expect(imports(cwd)).toEqual(['@import "yugen-ui/theme.css";']);
      expect(read(cwd, "src/yugen-ui.css")).toContain("src/App.tsx uses");
    }
    // Subpaths name their folder, even as a namespace or a dynamic import.
    const cwd = installYugen(viteProject({ "src/App.tsx": 'import * as D from "yugen-ui/Dialog";\nconst S = () => import("yugen-ui/AppShell/Sidebar");\n' }));
    expect((await css({ cwd })).folders).toEqual(["AppShell", "Dialog"]);
  });

  it("--src limits the scan and is kept in the header for the next run", async () => {
    const cwd = installYugen(
      viteProject({
        "src/feature/Page.tsx": 'import { Dialog } from "yugen-ui";\n',
        "src/other/Page.tsx": 'import { Button } from "yugen-ui";\n',
      }),
    );
    expect((await css({ cwd, src: ["src/feature"] })).folders).toEqual(["Dialog"]);
    const [generated] = findGenerated(cwd);
    expect(generated.recorded).toEqual({ src: ["src/feature"] });
    expect(read(cwd, "src/yugen-ui.css")).toContain("Generated by `yugen css --src src/feature`");
    expect((await css({ cwd })).folders).toEqual(["Dialog"]);
    expect(parseRecorded('/* Generated by `yugen css --src "my app" --precompile` */')).toEqual({ src: ["my app"], precompile: true });
    await expect(css({ cwd, src: ["nope"] })).rejects.toThrow(/not found/);
  });

  it("--out outside src / app / styles: later runs find the file and keep --out in the header", async () => {
    const cwd = installYugen(viteProject({ "src/App.tsx": 'import { Button } from "yugen-ui";\n' }));
    expect((await css({ cwd, out: "lib/yugen-ui.css" })).written).toBe(true);
    expect(read(cwd, "lib/yugen-ui.css")).toContain("Generated by `yugen css --out lib/yugen-ui.css`");
    expect(read(cwd, "src/index.css")).toBe('@import "tailwindcss";\n@import "../lib/yugen-ui.css";\n\nbody { margin: 0; }\n');
    // Same --out again: its own file, not "not written by yugen css".
    expect((await css({ cwd, out: "lib/yugen-ui.css", check: true })).ok).toBe(true);
    // The command the header records (predev / prebuild) finds it through src/index.css: no second file, no second import.
    fs.appendFileSync(path.join(cwd, "src/App.tsx"), 'import { Dialog } from "yugen-ui";\n');
    expect(await css({ cwd })).toMatchObject({ file: "lib/yugen-ui.css", folders: ["Button", "Dialog"], written: true });
    expect(fs.existsSync(path.join(cwd, "src/yugen-ui.css"))).toBe(false);
    expect(read(cwd, "src/index.css").match(/yugen-ui\.css/g)).toHaveLength(1);
    expect(findGenerated(cwd).map((g) => g.recorded)).toEqual([{ out: "lib/yugen-ui.css" }]);
  });

  it("without yugen-ui 0.14+ installed, the file imports theme.css until the next run", async () => {
    const cwd = viteProject({ "src/App.tsx": 'import { Button } from "yugen-ui";\n' });
    expect((await css({ cwd })).everything).toBe(true);
    expect(imports(cwd)).toEqual(['@import "yugen-ui/theme.css";']);
    installYugen(cwd);
    expect((await css({ cwd })).folders).toEqual(["Button"]);
  });

  it("refuses source mode, apps without Tailwind v4 and a file it did not write", async () => {
    const noTailwind = installYugen(
      writeFiles(tmpDir(), { "package.json": JSON.stringify({ dependencies: { react: "^19.3.1", "yugen-ui": "^0.15.0" } }), "src/main.tsx": "" }),
    );
    await expect(css({ cwd: noTailwind })).rejects.toThrow(/Tailwind CSS v4/);

    const source = viteProject({ "yugen.json": JSON.stringify({ mode: "source", framework: "vite", rsc: false, css: "src/index.css", paths: { ui: "src/components/ui", lib: "src/lib" } }) });
    await expect(css({ cwd: source })).rejects.toThrow(/npm package/);

    const taken = installYugen(viteProject({ "src/yugen-ui.css": ".mine {}\n" }));
    await expect(css({ cwd: taken })).rejects.toThrow(/not written by yugen css/);
    expect((await css({ cwd: taken, out: "src/styles/yugen.generated.css" })).file).toBe("src/styles/yugen.generated.css");
    expect(read(taken, "src/index.css")).toContain('@import "./styles/yugen.generated.css";');
  });

  it("--precompile needs the project's own Tailwind packages", async () => {
    const cwd = installYugen(
      writeFiles(tmpDir(), { "package.json": JSON.stringify({ dependencies: { react: "^19.3.1", "yugen-ui": "^0.15.0" } }), "src/main.tsx": "" }),
    );
    await expect(css({ cwd, precompile: true })).rejects.toSatisfy(
      (e: Error & { hint?: string }) => /not installed/.test(e.message) && /@tailwindcss\/node/.test(e.hint ?? ""),
    );
  });

  it("replaces hand-written theme-core.css + sources lines with one import", () => {
    const before = '@import "tailwindcss";\n/* @import "yugen-ui/theme.css"; */\n@import "yugen-ui/theme-core.css";\n@import "yugen-ui/sources/Button.css";\n@import "./brand.css";\n';
    expect(replaceThemeImports(before, "./yugen-ui.css")).toEqual({
      css: '@import "tailwindcss";\n/* @import "yugen-ui/theme.css"; */\n@import "./yugen-ui.css";\n@import "./brand.css";\n',
      removed: ['@import "yugen-ui/theme-core.css";', '@import "yugen-ui/sources/Button.css";'],
    });
    expect(replaceThemeImports('@import "tailwindcss";\n', "./yugen-ui.css")).toBeNull();
  });
});

describe("init + doctor with yugen-ui.css", () => {
  const VITE_MAIN = `import { createRoot } from "react-dom/client";
import "./index.css";
import App from "./App.tsx";

createRoot(document.getElementById("root")!).render(<App />);
`;

  it("init (package mode) writes yugen-ui.css after wrapping the provider, and keeps an existing theme.css import", async () => {
    const pkg = { name: "app", dependencies: { react: "^19.3.1", "yugen-ui": "^0.15.0" }, devDependencies: { tailwindcss: "^4.1.0" } };
    const cwd = installYugen(viteProject({ "package.json": JSON.stringify(pkg), "src/main.tsx": VITE_MAIN, "src/App.tsx": 'import { Button } from "yugen-ui";\n' }));
    await init({ cwd, mode: "package", install: false }, ctx);
    expect(read(cwd, "src/index.css")).toBe('@import "tailwindcss";\n@import "./yugen-ui.css";\n\nbody { margin: 0; }\n');
    expect(imports(cwd)).toEqual(['@import "yugen-ui/theme-core.css";', '@import "yugen-ui/sources/Button.css";', '@import "yugen-ui/sources/YugenProvider.css";']);
    const checks = await diagnose({ cwd, offline: true });
    expect(checks.filter((c) => c.level !== "ok")).toEqual([]);
    expect(checks.find((c) => c.message.startsWith("Theme imported"))?.message).toBe("Theme imported: src/index.css → ./yugen-ui.css");

    const old = installYugen(viteProject({ "src/index.css": '@import "tailwindcss";\n@import "yugen-ui/theme.css";\n' }));
    await init({ cwd: old, mode: "package", install: false }, ctx);
    expect(read(old, "src/index.css")).toBe('@import "tailwindcss";\n@import "yugen-ui/theme.css";\n');
    expect(fs.existsSync(path.join(old, "src/yugen-ui.css"))).toBe(false);

    // A src/yugen-ui.css that yugen css did not write: init still finishes, with theme.css.
    const taken = installYugen(viteProject({ "src/yugen-ui.css": ".mine {}\n" }));
    await init({ cwd: taken, mode: "package", install: false }, ctx);
    expect(read(taken, "src/index.css")).toBe('@import "tailwindcss";\n@import "yugen-ui/theme.css";\n\nbody { margin: 0; }\n');
    expect(read(taken, "src/yugen-ui.css")).toBe(".mine {}\n");
  });

  it("doctor accepts theme-core.css, warns about missing sources and a stale or unimported yugen-ui.css", async () => {
    const pkg = { name: "app", dependencies: { react: "^19.3.1", "yugen-ui": "^0.15.0" }, devDependencies: { tailwindcss: "^4.1.0" } };
    const cwd = installYugen(
      viteProject({
        "package.json": JSON.stringify(pkg),
        "src/index.css": '@import "tailwindcss";\n@import "yugen-ui/theme-core.css";\n@import "yugen-ui/sources/Button.css";\n',
        "src/App.tsx": 'import { Button, Dialog } from "yugen-ui";\n',
      }),
    );
    let checks = await diagnose({ cwd, offline: true });
    expect(checks.filter((c) => c.level === "error")).toEqual([]);
    expect(checks.find((c) => c.message.startsWith("Theme imported"))?.message).toBe("Theme imported: src/index.css → yugen-ui/theme-core.css");
    expect(checks.find((c) => c.message.startsWith("No CSS for"))).toMatchObject({ level: "warn", message: expect.stringContaining("Dialog") });

    await css({ cwd });
    expect(read(cwd, "src/index.css")).toBe('@import "tailwindcss";\n@import "./yugen-ui.css";\n');
    checks = await diagnose({ cwd, offline: true });
    expect(checks.filter((c) => c.level !== "ok" && !c.message.startsWith("YugenProvider"))).toEqual([]);
    expect(checks.find((c) => c.message.startsWith("src/yugen-ui.css"))?.message).toBe("src/yugen-ui.css is up to date (2 component folders)");

    fs.writeFileSync(path.join(cwd, "src/App.tsx"), 'import { Button, NavItem } from "yugen-ui";\n');
    checks = await diagnose({ cwd, offline: true });
    expect(checks.find((c) => c.message.startsWith("src/yugen-ui.css"))).toMatchObject({
      level: "warn",
      message: "src/yugen-ui.css is out of date: add Nav; remove Dialog",
    });

    fs.writeFileSync(path.join(cwd, "src/index.css"), '@import "tailwindcss";\n');
    checks = await diagnose({ cwd, offline: true });
    expect(checks.find((c) => c.message.includes("is not imported"))?.level).toBe("error");
    expect(checks.some((c) => c.message === "The Yugen theme is not imported")).toBe(false);
  });
});
