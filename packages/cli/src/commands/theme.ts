import path from "node:path";
// Bản sao nguyên văn của src/lib/brandRamp.ts (cùng thuật toán với Theme Designer); src/test/cli-brand-ramp.test.ts ở gốc repo
// báo lỗi nếu hai bản lệch.
import { adjustKeyForContrast, contrastRatio, generateBrandRamp, isHexColor, rampToCss } from "../lib/brandRamp.js";
import { loadConfig } from "../lib/config.js";
import { addCssImport } from "../lib/css.js";
import { CliError } from "../lib/errors.js";
import { exists, readText, toPosix, writeText } from "../lib/fs.js";
import { detectFramework, findCssFile, readPkg } from "../lib/project.js";
import { p, pc } from "../lib/ui.js";

export interface ThemeOptions {
  cwd: string;
  /** Màu key (brand80), HEX. */
  brand: string;
  /** Tên brand cho `data-brand` / `<YugenProvider brand>`. */
  name?: string;
  /** Độ rực 50–150 (%), mặc định 100. */
  vibrancy?: number;
  /** Xoắn hue −30…30 (độ), mặc định 0. */
  torsion?: number;
  css?: string;
  dryRun?: boolean;
}

export interface ThemeResult {
  file: string;
  css: string;
  /** Tương phản chữ trắng trên nút primary (light). */
  contrast: number;
}

const GENERATED = "/* Sinh bởi `yugen theme` — chạy lại lệnh để đổi màu, đừng sửa tay. Generated by `yugen theme`. */";

/**
 * Brand ramp 16 bậc từ một màu key → yugen-brand.css cạnh file CSS chính, và @import nó vào file đó. Không dùng yugen.css:
 * ở chế độ source đó là theme đã chép (`yugen init`).
 */
export function theme(opts: ThemeOptions): ThemeResult {
  const hex = opts.brand.startsWith("#") ? opts.brand : `#${opts.brand}`;
  if (!isHexColor(hex)) throw new CliError(`"${opts.brand}" is not a HEX colour.`, "Example: yugen theme --brand #0f6cbd");
  const name = (opts.name ?? "custom").toLowerCase();
  if (!/^[a-z][a-z0-9-]*$/.test(name)) throw new CliError(`Brand name "${opts.name}" is not valid.`, "Use lower-case letters, digits and dashes, e.g. --name acme");
  const vibrancy = opts.vibrancy ?? 100;
  const torsion = opts.torsion ?? 0;
  if (!(vibrancy >= 50 && vibrancy <= 150)) throw new CliError("--vibrancy must be between 50 and 150.");
  if (!(torsion >= -30 && torsion <= 30)) throw new CliError("--torsion must be between -30 and 30.");

  const pkg = readPkg(opts.cwd);
  if (!pkg) throw new CliError("No package.json found", "Run `yugen theme` in your project root.");
  const main = opts.css ?? loadConfig(opts.cwd)?.css ?? findCssFile(opts.cwd, detectFramework(pkg));
  if (!main || !exists(path.join(opts.cwd, main)))
    throw new CliError("Main CSS file not found.", 'Pass --css <file> — the file with @import "tailwindcss" and the Yugen theme.');

  const ramp = generateBrandRamp(hex, { vibrancy: vibrancy / 100, hueTorsion: torsion });
  const css = `${GENERATED}\n${rampToCss(name, ramp)}\n`;
  const file = toPosix(path.join(path.dirname(main), "yugen-brand.css"));
  const contrast = contrastRatio(ramp[7], "#ffffff");

  if (opts.dryRun) {
    console.log(css);
    p.log.info(pc.dim(`Dry run: would write ${file} and import it from ${main}.`));
  } else {
    writeText(path.join(opts.cwd, file), css);
    const mainAbs = path.join(opts.cwd, main);
    const { css: updated, changed } = addCssImport(readText(mainAbs), "./yugen-brand.css");
    if (changed) writeText(mainAbs, updated);
    p.log.success(`Wrote ${file}${changed ? ` and imported it from ${main}` : ""}`);
  }

  if (contrast < 4.5)
    p.log.warn(
      `White text on the primary button is ${contrast.toFixed(2)}:1, under 4.5:1.\n` +
        pc.dim(`A darker key that passes: yugen theme --brand ${adjustKeyForContrast(hex)}${opts.name ? ` --name ${name}` : ""}`),
    );
  p.note(pc.cyan(`<YugenProvider applyToDocument withToaster brand="${name}">`), "Use the brand");
  return { file, css, contrast };
}
