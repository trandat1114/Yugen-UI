/**
 * CSS chỉ gồm các component app dùng (#169). `yugen-ui/theme.css` cho Tailwind quét mọi component của gói; file do
 * `yugen css` ghi thay nó bằng `theme-core.css` + `sources/<Thư mục>.css` cho từng thư mục component mà mã của app import.
 * Bảng tên export → thư mục là `yugen-ui/sources/index.json` (scripts/build-css.mjs ở gốc repo, từ yugen-ui 0.14.0).
 */

