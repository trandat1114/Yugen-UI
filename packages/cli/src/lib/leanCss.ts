/** Gói Tailwind mà `--precompile` mượn của dự án. */
export const PRECOMPILE_DEPS = ["tailwindcss", "@tailwindcss/node", "@tailwindcss/oxide"];

export interface Manifest {
  version: string;
  /** Tên export (có giá trị) → thư mục component. */
  exports: Record<string, string>;
  /** Thư mục → các đường dẫn file sources/<Thư mục>.css quét. */
  sources: Record<string, string[]>;
  /** Token groups outside theme-core.css → file in the package (#354), e.g. brands → tokens/brands.css. */
  tokens?: Record<string, string>;
}

/**
 * `yugen-ui/sources/index.json` của bản đã cài (tìm cả node_modules của thư mục cha), qua `exports` của gói
 * (`./sources/*` → `./dist/sources/*`). null nếu chưa cài hoặc bản trước 0.14.0.
 */
export function readManifest(cwd: string): Manifest | null {
  for (let dir = path.resolve(cwd); ; dir = path.dirname(dir)) {
    const root = path.join(dir, "node_modules", PACKAGE);
    if (exists(path.join(root, "package.json"))) {
      try {
        const pkg = JSON.parse(readText(path.join(root, "package.json"))) as { exports?: Record<string, unknown> };
        const target = pkg.exports?.["./sources/*"];
        if (typeof target !== "string") return null;
        const file = path.join(root, target.replace("*", "index.json"));
        return exists(file) ? (JSON.parse(readText(file)) as Manifest) : null;
      } catch {
        return null;
      }
    }
    if (path.dirname(dir) === dir) return null;
  }
}

/** Lý do phải dùng theme.css: một import có thể dùng mọi component. */
export interface Everything {
  file: string;
  syntax: string;
}

export interface Usage {
  /** Thư mục component được import, đã sắp xếp. */
  folders: string[];
  everything: Everything | null;
  /** Token files to import after theme-core.css (#354), e.g. tokens/brands.css when the app sets brand web / teams. */
  tokens?: string[];
  /** Số file mã đã đọc. */
  files: number;
}

/** brand="web" | "teams" on YugenProvider, `brand: "teams"` in an object, or data-brand="web" in markup (#354). */
const OTHER_BRAND = /\b(?:data-)?brand\s*[=:]\s*\{?\s*["'`](?:web|teams)["'`]/;

const SKIP_DIRS = new Set(["node_modules", "dist", "build", "out", "coverage", "public", "storybook-static"]);
const MAX_BYTES = 2 * 1024 * 1024;

/**
 * File mã trong `dir`, kể cả test và story (thừa một thư mục chỉ thêm ít CSS, thiếu thì component mất style). Bỏ
 * node_modules, bản build, public, thư mục ẩn (trừ .storybook), .d.ts và .min.js.
 */
function codeFiles(dir: string): string[] {
  const out: string[] = [];
  const visit = (d: string, depth: number) => {
    let entries: fs.Dirent[];
    try {
      entries = fs.readdirSync(d, { withFileTypes: true });
    } catch {
      return;
    }
    for (const e of entries) {
      const full = path.join(d, e.name);
      if (e.isDirectory()) {
        if ((!e.name.startsWith(".") || e.name === ".storybook") && !SKIP_DIRS.has(e.name) && depth < 12) visit(full, depth + 1);
      } else if (CODE_FILE.test(e.name) && !/\.d\.[cm]?ts$|\.min\.js$/.test(e.name)) out.push(full);
    }
  };
  visit(dir, 0);
  return out.sort();
}

const SYNTAX: Record<ModuleImport["kind"], string> = {
  namespace: "import * as",
  star: "export *",
  dynamic: "import()",
  require: "require()",
  named: "default import",
  "side-effect": "",
};

/** Thư mục component của một import từ yugen-ui; "all" nếu nó có thể dùng mọi component; null nếu không phải yugen-ui. */
export function importFolders(imp: ModuleImport, manifest: Manifest): string[] | "all" | null {
  if (imp.from === PACKAGE) {
    // Gói không có export mặc định; `import Y from "yugen-ui"` coi như import cả gói.
    if (imp.all || imp.names.includes("default")) return "all";
    return [...new Set(imp.names.flatMap((n) => (Object.hasOwn(manifest.exports, n) ? [manifest.exports[n]] : [])))];
  }
  if (!imp.from.startsWith(`${PACKAGE}/`)) return null;
  // yugen-ui/Button, yugen-ui/AppShell/Sidebar, yugen-ui/hooks → thư mục đầu; theme.css, messages-en… không có sources.
  const folder = imp.from.slice(PACKAGE.length + 1).split("/")[0];
  return Object.hasOwn(manifest.sources, folder) ? [folder] : [];
}

/** Đọc import yugen-ui trong `dirs` (tương đối với `cwd`). */
export function scanUsage(cwd: string, dirs: string[], manifest: Manifest): Usage {
  const folders = new Set<string>();
  const tokens = new Set<string>();
  let everything: Everything | null = null;
  let files = 0;
  for (const dir of dirs) {
    for (const file of codeFiles(path.resolve(cwd, dir))) {
      let code: string;
      try {
        if (fs.statSync(file).size > MAX_BYTES) continue;
        code = readText(file);
      } catch {
        continue;
      }
      files++;
      if (manifest.tokens?.brands && OTHER_BRAND.test(code)) tokens.add(manifest.tokens.brands);
      if (!code.includes(PACKAGE)) continue;
      for (const imp of findImports(code, file)) {
        const found = importFolders(imp, manifest);
        if (found === "all") everything ??= { file: toPosix(path.relative(cwd, file)), syntax: SYNTAX[imp.kind] };
        else if (found) for (const f of found) folders.add(f);
      }
    }
  }
  return { folders: [...folders].sort(), everything, tokens: [...tokens].sort(), files };
}

/** Tên do người dùng gõ (`data-grid`, `DataGrid`, `NavItem`) → thư mục component, hoặc null. */
export function folderOfName(name: string, manifest: Manifest): string | null {
  const pascal = name.replace(/(^|[-_\s]+)(\w)/g, (_m, _sep, c: string) => c.toUpperCase());
  for (const n of [name, pascal]) if (Object.hasOwn(manifest.exports, n)) return manifest.exports[n];
  const lower = pascal.toLowerCase();
  return Object.keys(manifest.sources).find((f) => f.toLowerCase() === lower) ?? null;
}

/** Tuỳ chọn được ghi lại trong đầu file sinh ra, để `yugen css` / `add` / `doctor` chạy lại đúng như lần trước. */
export interface Recorded {
  src?: string[];
  /** Chỉ khi người dùng truyền `--out`: lệnh in ra (predev, --check) phải trỏ đúng file. */
  out?: string;
  precompile?: boolean;
}

const quoteArg = (a: string) => (/[\s"`]/.test(a) ? `"${a.replace(/"/g, "")}"` : a);

/** `yugen css --src app --precompile`: lệnh tạo ra file, ghi ở dòng đầu. */
export function commandOf(r: Recorded) {
  return [
    "yugen css",
    ...(r.src ?? []).flatMap((d) => ["--src", quoteArg(d)]),
    ...(r.out ? ["--out", quoteArg(r.out)] : []),
    ...(r.precompile ? ["--precompile"] : []),
  ].join(" ");
}

/** Đọc lại tuỳ chọn từ đầu file; null nếu file không do `yugen css` ghi. */
export function parseRecorded(text: string): Recorded | null {
  const m = text.match(/Generated by `(yugen css[^`]*)`/);
  if (!m) return null;
  const args = [...m[1].matchAll(/"([^"]*)"|(\S+)/g)].map((a) => a[1] ?? a[2]).slice(2);
  const r: Recorded = {};
  for (let i = 0; i < args.length; i++) {
    if (args[i] === "--src" && args[i + 1] !== undefined) (r.src ??= []).push(args[++i]);
    else if (args[i] === "--out" && args[i + 1] !== undefined) r.out = args[++i];
    else if (args[i] === "--precompile") r.precompile = true;
  }
  return r;
}

function header(r: Recorded, notes: string[]) {
  return [
    "/*",
    ` * Generated by \`${commandOf(r)}\` from the yugen-ui imports in your code. Don't edit it by hand:`,
    " * run the command again after you import another component (`yugen add` does it for you).",
    ...notes.map((n) => ` * ${n}`),
    " */",
  ].join("\n");
}

const everythingNote = (e: Everything) => `${e.file} uses \`${e.syntax}\` from "${PACKAGE}", which can reach any component.`;

/** Nội dung file `@import` cho Tailwind v4. Không có bảng sources (chưa cài yugen-ui / bản cũ) → theme.css. */
export function importsCss(r: Recorded, usage: Usage | null): string {
  if (!usage) return `${header(r, ["yugen-ui 0.14.0 or later is not installed yet, so this file imports theme.css (every component)."])}\n@import "${THEME}";\n`;
  if (usage.everything) return `${header(r, [everythingNote(usage.everything), "So this file imports theme.css (every component)."])}\n@import "${THEME}";\n`;
  return [header(r, []), ...leanImports(usage), ""].join("\n");
}

/** `@import` lines of the lean path: theme-core.css, the token groups the app needs, one sources file per folder. */
export function leanImports(usage: Usage): string[] {
  return [
    `@import "${THEME_CORE}";`,
    ...(usage.tokens ?? []).map((t) => `@import "${PACKAGE}/${t}";`),
    ...usage.folders.map((f) => `@import "${PACKAGE}/sources/${f}.css";`),
  ];
}

/** Dòng mô tả bản biên dịch (`--precompile`): phiên bản và thư mục, để doctor biết file đã cũ mà không cần biên dịch lại. */
export const precompiledMeta = (version: string, tailwind: string, usage: Usage) =>
  `yugen-ui ${version}, Tailwind CSS ${tailwind}: ${usage.everything ? "every component" : usage.folders.join(", ") || "no component"}`;

export function precompiledCss(r: Recorded, meta: string, usage: Usage, compiled: string) {
  return `${header(r, [...(usage.everything ? [everythingNote(usage.everything)] : []), meta])}\n${compiled.trim()}\n`;
}

/** Thư mục được liệt kê trong một file đã sinh (để báo thêm / bớt gì). */
export function listedFolders(text: string): string[] | "all" {
  if (/^@import\s+"yugen-ui\/theme\.css"/m.test(text) || /: every component$/m.test(text)) return "all";
  const imported = [...text.matchAll(/^@import\s+"yugen-ui\/sources\/([^"]+)\.css"/gm)].map((m) => m[1]);
  if (imported.length) return imported;
  const meta = text.match(/^ \* yugen-ui \S+, Tailwind CSS \S+: (.*)$/m)?.[1];
  return meta && meta !== "no component" ? meta.split(", ") : [];
}

/** "thêm Dialog, Menu; bớt Tabs" giữa hai danh sách thư mục, hoặc "" nếu như nhau. */
export function folderChange(before: string[] | "all", after: string[] | "all") {
  if (before === "all" || after === "all") return before === after ? "" : after === "all" ? "now every component (theme.css)" : "no longer every component";
  const added = after.filter((f) => !before.includes(f));
  const removed = before.filter((f) => !after.includes(f));
  return [added.length ? `add ${added.join(", ")}` : "", removed.length ? `remove ${removed.join(", ")}` : ""].filter(Boolean).join("; ");
}

export interface Generated {
  /** Đường dẫn tương đối với dự án, kiểu posix. */
  file: string;
  abs: string;
  text: string;
  recorded: Recorded;
}

/** File do `yugen css` ghi (đọc đầu file), hoặc null. */
export function readGenerated(cwd: string, abs: string): Generated | null {
  if (!exists(abs)) return null;
  const text = readText(abs);
  const recorded = text.slice(0, 600).includes(MARK) ? parseRecorded(text) : null;
  return recorded ? { file: toPosix(path.relative(cwd, abs)), abs, text, recorded } : null;
}

/**
 * File CSS của dự án mà `yugen css` đã ghi: trong src, app, styles và gốc, cùng file mà các CSS đó `@import` (file ghi
 * bằng `--out` ở thư mục khác, vd. `@import "../lib/yugen-ui.css"`).
 */
export function findGenerated(cwd: string): Generated[] {
  const scanned = [...walk(cwd, /\.css$/, 0), ...["src", "app", "styles"].flatMap((d) => walk(path.join(cwd, d), /\.css$/, 5))];
  const linked = scanned.flatMap((f) =>
    cssImports(readText(f)).flatMap((spec) => (spec.startsWith(".") && spec.endsWith(".css") ? [path.resolve(path.dirname(f), spec)] : [])),
  );
  return [...new Set([...scanned, ...linked])].sort().flatMap((abs) => readGenerated(cwd, abs) ?? []);
}

/** Đường dẫn tương đối `spec` viết trong file `from` trỏ tới file `target` (tuyệt đối)? */
export const specResolvesTo = (from: string, spec: string, target: string) =>
  spec.startsWith(".") && path.resolve(path.dirname(from), spec) === path.resolve(target);

/** CSS `importer` có `@import` trỏ tới file `target`? */
export const cssImportsFile = (importer: string, css: string, target: string) => cssImports(css).some((spec) => specResolvesTo(importer, spec, target));

/** Mã `importer` có import file `target` (vd. `import "./yugen-ui.css"`)? */
export const codeImportsFile = (importer: string, code: string, target: string) =>
  code.includes(path.basename(target)) && findImports(code, importer).some((i) => specResolvesTo(importer, i.from, target));

const YUGEN_LINE = /^[ \t]*@import\s+(?:url\(\s*)?["']yugen-ui\/(?:theme|theme-core)\.css["']|^[ \t]*@import\s+(?:url\(\s*)?["']yugen-ui\/sources\/[^"']+["']/;

/**
 * Thay các dòng `@import "yugen-ui/theme.css"` / `theme-core.css` / `sources/*.css` bằng một dòng `@import "<spec>";` ở chỗ
 * dòng đầu tiên. Không có dòng nào thì trả về null.
 */
export function replaceThemeImports(css: string, spec: string): { css: string; removed: string[] } | null {
  const eol = css.includes("\r\n") ? "\r\n" : "\n";
  const lines = css.split(/\r?\n/);
  // Chỉ xét dòng ngoài chú thích: chú thích thành khoảng trắng, giữ nguyên số dòng.
  const visible = css.replace(/\/\*[\s\S]*?\*\//g, (c) => c.replace(/[^\r\n]/g, " ")).split(/\r?\n/);
  const hits = lines.flatMap((_, i) => (YUGEN_LINE.test(visible[i] ?? "") ? [i] : []));
  if (!hits.length) return null;
  const removed = hits.map((i) => lines[i].trim());
  const out = lines.flatMap((line, i) => (i === hits[0] ? [`@import "${spec}";`] : hits.includes(i) ? [] : [line]));
  return { css: out.join(eol), removed };
}
